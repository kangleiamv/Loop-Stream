import path from 'path';
import fs from 'fs/promises';
import fsSync from 'fs';
import { exec } from 'child_process';
import { promisify } from 'util';
import { getSetting, setSetting, deleteSetting, logActivity } from './database';

const execAsync = promisify(exec);

export interface CookieItem {
  domain?: string;
  hostOnly?: boolean;
  httpOnly?: boolean;
  name: string;
  path?: string;
  sameSite?: string;
  secure?: boolean;
  session?: boolean;
  storeId?: string;
  value: string;
  expirationDate?: number;
  expiry?: number;
  expires?: number;
  [key: string]: any;
}

export interface CookieStatus {
  configured: boolean;
  totalCount: number;
  youtubeCount: number;
  hasAuthCookies: boolean;
  detectedAuthCookies: string[];
  updatedAt: string | null;
  fileSize: number;
  rawJson: string;
  source: 'file' | 'db' | 'none';
}

export function getCookiePaths() {
  const dbPath = process.env.DATABASE_PATH || './data/streams.db';
  const dataDir = path.resolve(path.dirname(dbPath));
  return {
    dataDir,
    jsonPath: path.join(dataDir, 'cookies.json'),
    netscapePath: path.join(dataDir, 'cookies.txt'),
  };
}

/**
 * Convert JSON array of cookies (e.g. from Cookie-Editor extension)
 * to Netscape HTTP Cookie File format compatible with curl and yt-dlp.
 */
export function jsonToNetscape(cookies: CookieItem[]): string {
  const lines: string[] = [
    '# Netscape HTTP Cookie File',
    '# https://curl.se/docs/http-cookies.html',
    '# This file was generated by LOOP STREAM. Do not edit directly.',
    '',
  ];

  for (const c of cookies) {
    if (!c || !c.name) continue;

    let domain = (c.domain || '.youtube.com').trim();
    const isHttpOnly = Boolean(c.httpOnly);
    if (isHttpOnly && !domain.startsWith('#HttpOnly_')) {
      domain = `#HttpOnly_${domain}`;
    }

    const domainWithoutPrefix = domain.replace(/^#HttpOnly_/, '');
    const includeSub = domainWithoutPrefix.startsWith('.') ? 'TRUE' : 'FALSE';
    const cookiePath = c.path || '/';
    const isSecure = c.secure ? 'TRUE' : 'FALSE';

    let exp = 2147483647; // Unix timestamp 2038 fallback
    const rawExp = c.expirationDate ?? c.expiry ?? c.expires;
    if (rawExp && typeof rawExp === 'number') {
      exp = Math.floor(rawExp);
    } else if (rawExp && typeof rawExp === 'string') {
      const parsed = parseInt(rawExp, 10);
      if (!isNaN(parsed)) exp = parsed;
    }

    const name = String(c.name).replace(/[\t\r\n]/g, '');
    const value = String(c.value ?? '').replace(/[\r\n]/g, '');

    lines.push(`${domain}\t${includeSub}\t${cookiePath}\t${isSecure}\t${exp}\t${name}\t${value}`);
  }

  return lines.join('\n') + '\n';
}

/**
 * Convert Netscape text format to array of CookieItem
 */
export function netscapeToJson(text: string): CookieItem[] {
  const lines = text.split(/\r?\n/);
  const cookies: CookieItem[] = [];

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || (trimmed.startsWith('#') && !trimmed.startsWith('#HttpOnly_'))) {
      continue;
    }

    const isHttpOnly = trimmed.startsWith('#HttpOnly_');
    const cleanLine = isHttpOnly ? trimmed.substring(10) : trimmed;
    const parts = cleanLine.split('\t');
    if (parts.length < 7) continue;

    const [domain, , cookiePath, secureStr, expStr, name, ...valueParts] = parts;
    const value = valueParts.join('\t');
    const exp = parseInt(expStr, 10);

    cookies.push({
      domain,
      httpOnly: isHttpOnly,
      path: cookiePath || '/',
      secure: secureStr.toUpperCase() === 'TRUE',
      expirationDate: isNaN(exp) ? undefined : exp,
      name,
      value,
    });
  }

  return cookies;
}

/**
 * Parse any cookie input (JSON string, JSON array, JSON object, or Netscape format text)
 */
export function parseCookieInput(input: any): CookieItem[] {
  if (!input) {
    throw new Error('Cookie content cannot be empty.');
  }

  if (typeof input === 'string') {
    const trimmed = input.trim();
    if (!trimmed) {
      throw new Error('Cookie content cannot be empty.');
    }

    if (
      trimmed.startsWith('# Netscape') ||
      (trimmed.includes('\t') && !trimmed.startsWith('{') && !trimmed.startsWith('['))
    ) {
      const parsedNetscape = netscapeToJson(trimmed);
      if (parsedNetscape.length === 0) {
        throw new Error('No valid cookies found in Netscape format.');
      }
      return parsedNetscape;
    }

    try {
      const parsedJson = JSON.parse(trimmed);
      return parseCookieInput(parsedJson);
    } catch (jsonErr: any) {
      throw new Error(`Invalid JSON syntax: ${jsonErr.message}`);
    }
  }

  if (Array.isArray(input)) {
    const valid = input
      .filter((item) => item && typeof item === 'object' && typeof item.name === 'string')
      .map((item) => ({
        domain: item.domain || '.youtube.com',
        path: item.path || '/',
        secure: item.secure !== undefined ? Boolean(item.secure) : true,
        httpOnly: item.httpOnly !== undefined ? Boolean(item.httpOnly) : false,
        name: String(item.name).trim(),
        value: String(item.value ?? ''),
        expirationDate: item.expirationDate ?? item.expiry ?? item.expires,
        sameSite: item.sameSite,
      }));

    if (valid.length === 0) {
      throw new Error('JSON array does not contain any valid cookie objects with a "name" field.');
    }
    return valid;
  }

  if (typeof input === 'object' && input !== null) {
    if (Array.isArray(input.cookies)) {
      return parseCookieInput(input.cookies);
    }

    // Key-value pairs
    const cookies: CookieItem[] = [];
    for (const [key, value] of Object.entries(input)) {
      if (typeof value === 'string') {
        cookies.push({
          domain: '.youtube.com',
          path: '/',
          secure: true,
          name: key,
          value,
        });
      }
    }
    if (cookies.length === 0) {
      throw new Error('Object does not contain any valid key-value cookie pairs.');
    }
    return cookies;
  }

  throw new Error('Unsupported cookie format. Please provide a JSON array exported from Cookie-Editor.');
}

/**
 * Check if the cookie array has crucial YouTube authentication cookies
 */
export function analyzeCookies(cookies: CookieItem[]) {
  const youtubeAuthNames = new Set([
    '__Secure-1PSID',
    '__Secure-3PSID',
    'LOGIN_INFO',
    'SID',
    'HSID',
    'SSID',
    'APISID',
    'SAPISID',
    'VISITOR_INFO1_LIVE',
    'PREF',
    '__Secure-1PAPISID',
    '__Secure-3PAPISID',
  ]);

  let youtubeCount = 0;
  let hasAuthCookies = false;
  const detectedAuthCookies: string[] = [];

  for (const c of cookies) {
    const domain = (c.domain || '').toLowerCase();
    if (domain.includes('youtube.com') || domain.includes('google.com')) {
      youtubeCount++;
      if (youtubeAuthNames.has(c.name)) {
        hasAuthCookies = true;
        if (!detectedAuthCookies.includes(c.name)) {
          detectedAuthCookies.push(c.name);
        }
      }
    }
  }

  return {
    totalCount: cookies.length,
    youtubeCount,
    hasAuthCookies,
    detectedAuthCookies,
  };
}

/**
 * Save cookies to cookies.json and cookies.txt on disk and in database
 */
export async function saveCookies(input: any): Promise<CookieStatus> {
  const cookies = parseCookieInput(input);
  const prettyJson = JSON.stringify(cookies, null, 2);
  const netscapeText = jsonToNetscape(cookies);

  const { dataDir, jsonPath, netscapePath } = getCookiePaths();

  await fs.mkdir(dataDir, { recursive: true });
  await fs.writeFile(jsonPath, prettyJson, 'utf8');
  await fs.writeFile(netscapePath, netscapeText, 'utf8');

  // Persist to database settings
  try {
    await setSetting('youtube_cookies_json', prettyJson);
    await setSetting('youtube_cookies_netscape', netscapeText);
    await logActivity('settings_update', `Updated YouTube cookies.json (${cookies.length} cookies)`);
  } catch (dbErr) {
    console.warn('Could not persist cookies to DB settings table:', dbErr);
  }

  const analysis = analyzeCookies(cookies);
  const stat = await fs.stat(jsonPath);

  return {
    configured: true,
    totalCount: analysis.totalCount,
    youtubeCount: analysis.youtubeCount,
    hasAuthCookies: analysis.hasAuthCookies,
    detectedAuthCookies: analysis.detectedAuthCookies,
    updatedAt: stat.mtime.toISOString(),
    fileSize: stat.size,
    rawJson: prettyJson,
    source: 'file',
  };
}

/**
 * Load cookies from disk or database fallback
 */
export async function loadCookies(): Promise<CookieStatus> {
  const { dataDir, jsonPath, netscapePath } = getCookiePaths();

  // 1. Try reading from filesystem
  try {
    if (fsSync.existsSync(jsonPath)) {
      const content = await fs.readFile(jsonPath, 'utf8');
      const cookies = parseCookieInput(content);
      const stat = await fs.stat(jsonPath);
      const analysis = analyzeCookies(cookies);

      // Ensure netscape file is also present
      if (!fsSync.existsSync(netscapePath)) {
        await fs.writeFile(netscapePath, jsonToNetscape(cookies), 'utf8');
      }

      return {
        configured: true,
        totalCount: analysis.totalCount,
        youtubeCount: analysis.youtubeCount,
        hasAuthCookies: analysis.hasAuthCookies,
        detectedAuthCookies: analysis.detectedAuthCookies,
        updatedAt: stat.mtime.toISOString(),
        fileSize: stat.size,
        rawJson: content,
        source: 'file',
      };
    }
  } catch (fsErr) {
    console.warn('Error reading cookies from file:', fsErr);
  }

  // 2. Try restoring from database settings
  try {
    const dbJson = await getSetting('youtube_cookies_json');
    if (dbJson) {
      const cookies = parseCookieInput(dbJson);
      const analysis = analyzeCookies(cookies);
      const prettyJson = JSON.stringify(cookies, null, 2);
      const netscapeText = jsonToNetscape(cookies);

      await fs.mkdir(dataDir, { recursive: true });
      await fs.writeFile(jsonPath, prettyJson, 'utf8');
      await fs.writeFile(netscapePath, netscapeText, 'utf8');

      return {
        configured: true,
        totalCount: analysis.totalCount,
        youtubeCount: analysis.youtubeCount,
        hasAuthCookies: analysis.hasAuthCookies,
        detectedAuthCookies: analysis.detectedAuthCookies,
        updatedAt: new Date().toISOString(),
        fileSize: Buffer.byteLength(prettyJson),
        rawJson: prettyJson,
        source: 'db',
      };
    }
  } catch (dbErr) {
    console.warn('Error reading cookies from DB:', dbErr);
  }

  return {
    configured: false,
    totalCount: 0,
    youtubeCount: 0,
    hasAuthCookies: false,
    detectedAuthCookies: [],
    updatedAt: null,
    fileSize: 0,
    rawJson: '',
    source: 'none',
  };
}

/**
 * Delete cookies from disk and database
 */
export async function deleteCookies(): Promise<void> {
  const { jsonPath, netscapePath } = getCookiePaths();

  try {
    await fs.unlink(jsonPath);
  } catch {}

  try {
    await fs.unlink(netscapePath);
  } catch {}

  try {
    await deleteSetting('youtube_cookies_json');
    await deleteSetting('youtube_cookies_netscape');
    await logActivity('settings_update', 'Cleared YouTube cookies');
  } catch {}
}

/**
 * Get the yt-dlp --cookies argument if cookies exist
 */
export async function getYtDlpCookieFlag(): Promise<string> {
  const { jsonPath, netscapePath } = getCookiePaths();

  if (fsSync.existsSync(netscapePath)) {
    try {
      const stat = await fs.stat(netscapePath);
      if (stat.size > 20) {
        return `--cookies "${netscapePath}"`;
      }
    } catch {}
  }

  if (fsSync.existsSync(jsonPath)) {
    try {
      const stat = await fs.stat(jsonPath);
      if (stat.size > 5) {
        const content = await fs.readFile(jsonPath, 'utf8');
        const cookies = parseCookieInput(content);
        const netscape = jsonToNetscape(cookies);
        await fs.writeFile(netscapePath, netscape, 'utf8');
        return `--cookies "${netscapePath}"`;
      }
    } catch {}
  }

  // Check DB fallback
  try {
    const dbJson = await getSetting('youtube_cookies_json');
    if (dbJson) {
      const cookies = parseCookieInput(dbJson);
      const netscape = jsonToNetscape(cookies);
      await fs.writeFile(netscapePath, netscape, 'utf8');
      return `--cookies "${netscapePath}"`;
    }
  } catch {}

  return '';
}

/**
 * Get base yt-dlp command with Deno runtime and cookies flag included
 */
export async function getBaseYtDlpCmd(): Promise<string> {
  const cookieFlag = await getYtDlpCookieFlag();
  const denoFlag = fsSync.existsSync('/usr/local/bin/deno')
    ? '--js-runtimes "deno:/usr/local/bin/deno"'
    : '--js-runtimes deno';

  return `yt-dlp ${denoFlag} ${cookieFlag} --no-playlist`.replace(/\s+/g, ' ').trim();
}

/**
 * Format error message from yt-dlp into a clear human-readable string
 */
export function formatYtDlpError(err: any): { message: string; requiresCookies: boolean; isPrivate: boolean } {
  const msg = (err.stderr || err.stdout || err.message || '').toString();

  if (
    msg.includes("Sign in to confirm you're not a bot") ||
    msg.includes('Sign in to confirm you’re not a bot') ||
    msg.includes('Use --cookies-from-browser or --cookies') ||
    msg.includes('confirm you’re not a bot') ||
    msg.includes("confirm you're not a bot") ||
    msg.includes('bot verification')
  ) {
    return {
      message:
        'YouTube requires bot verification / sign-in. Please export your YouTube cookies.json using Cookie-Editor and paste or upload them in Settings.',
      requiresCookies: true,
      isPrivate: false,
    };
  }

  if (msg.includes('Private video')) {
    return {
      message:
        'This video is private. If you have access to this video, make sure your cookies.json includes the logged-in session cookies for the authorized YouTube account.',
      requiresCookies: true,
      isPrivate: true,
    };
  }

  if (msg.includes('Video unavailable')) {
    return {
      message: 'Video is unavailable, region-locked, or deleted on YouTube.',
      requiresCookies: false,
      isPrivate: false,
    };
  }

  if (msg.includes('Members-only content')) {
    return {
      message: 'This video is members-only. Your YouTube cookies must belong to an account with an active channel membership.',
      requiresCookies: true,
      isPrivate: true,
    };
  }

  if (msg.includes('Premieres in')) {
    return {
      message: 'This YouTube video is an upcoming premiere and is not yet available to watch.',
      requiresCookies: false,
      isPrivate: false,
    };
  }

  if (msg.includes('ETIMEDOUT') || msg.includes('timed out')) {
    return {
      message: 'Connection timed out while contacting YouTube servers.',
      requiresCookies: false,
      isPrivate: false,
    };
  }

  // Clean the error output
  const lines = msg.split('\n');
  const errorLine = lines.find((l: string) => l.startsWith('ERROR:')) || msg.substring(0, 200);
  return {
    message: errorLine.replace(/^ERROR:\s*/, '').trim() || 'Failed to extract video information from YouTube.',
    requiresCookies: false,
    isPrivate: false,
  };
}

/**
 * Test extraction of a YouTube video using current cookies
 */
export async function testYouTubeCookies(testUrl = 'https://www.youtube.com/watch?v=dQw4w9WgXcQ') {
  try {
    const baseCmd = await getBaseYtDlpCmd();
    const sanitizedUrl = testUrl.replace(/(["'$`\\])/g, '\\$1');
    const cmd = `${baseCmd} -j --skip-download "${sanitizedUrl}"`;

    const { stdout } = await execAsync(cmd, { timeout: 30000 });
    const lines = stdout.trim().split('\n');

    let info: any = null;
    for (const line of lines) {
      try {
        const parsed = JSON.parse(line.trim());
        if (parsed && (parsed.id || parsed.title)) {
          info = parsed;
          break;
        }
      } catch {}
    }

    if (!info) {
      throw new Error('yt-dlp returned no valid JSON data.');
    }

    return {
      success: true,
      id: info.id,
      title: info.title,
      uploader: info.uploader || info.channel || 'Unknown',
      thumbnail: info.thumbnail,
      duration: info.duration,
      durationFormatted: info.duration_string || `${info.duration}s`,
      resolution: info.resolution || (info.height ? `${info.height}p` : 'HD'),
      viewCount: info.view_count,
      message: 'YouTube video information extracted successfully!',
    };
  } catch (err: any) {
    const formatted = formatYtDlpError(err);
    return {
      success: false,
      error: formatted.message,
      requiresCookies: formatted.requiresCookies,
      isPrivate: formatted.isPrivate,
      rawError: err.stderr || err.message,
    };
  }
}
